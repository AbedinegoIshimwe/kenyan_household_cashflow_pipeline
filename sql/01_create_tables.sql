-- The cleaned CSV contains 58 source fields plus source_row_number.
-- trx_id is repeated in the data, so source_row_number is the surrogate key.
-- Source names account_ids and trx_family_desc are used as present in the CSV.
CREATE TABLE IF NOT EXISTS public.transactions (
    source_row_number BIGINT PRIMARY KEY,
    hh_ids TEXT NOT NULL,
    unique_hhs SMALLINT,
    first_trx_date_hh TEXT,
    last_trx_date_hh TEXT,
    tot_hh_daysofobs INTEGER,
    tot_hh_monthsofobs INTEGER,
    interview_designation TEXT,
    int_date TEXT,
    int_month SMALLINT,
    int_year SMALLINT,
    int_yr_mo TEXT,
    first_int_date TEXT,
    account_ids TEXT,
    unique_accnts SMALLINT,
    m_ids_owner TEXT,
    unique_hm_owner SMALLINT,
    account_bsheet_desig TEXT,
    account_startclose_balance TEXT,
    account_formal TEXT,
    account_liquid TEXT,
    first_trx_date_acc TEXT,
    last_trx_date_acc TEXT,
    tot_acc_daysofobs INTEGER,
    tot_acc_monthsofobs INTEGER,
    trx_id TEXT,
    m_ids_trx TEXT,
    trx_date DATE NOT NULL,
    trx_month SMALLINT,
    trx_year SMALLINT,
    trx_yr_mo TEXT,
    trx_dq_round SMALLINT,
    trx_stdtime_days_hh INTEGER,
    trx_stdtime_mnths_hh INTEGER,
    trx_stdtime_days_acc INTEGER,
    trx_stdtime_mnths_acc INTEGER,
    trx_class_code TEXT,
    trx_class_desc TEXT,
    trx_family_code TEXT,
    trx_family_desc TEXT,
    trx_type_code INTEGER,
    trx_type_desc TEXT,
    trx_prx_purpose TEXT,
    trx_prx_purpose_fd TEXT,
    trx_fee NUMERIC(18, 6),
    trx_bsheet_direction TEXT,
    trx_mode_code SMALLINT,
    trx_mode_desc TEXT,
    trx_place_incommunity SMALLINT,
    trx_distance_km NUMERIC(18, 6),
    trx_outlet TEXT,
    trx_direction TEXT NOT NULL
        CHECK (trx_direction IN ('Inflow', 'Outflow')),
    trx_value_kes NUMERIC(18, 2) NOT NULL,
    trx_value_usd NUMERIC(18, 6),
    ddd_gift SMALLINT,
    trx_inkind_units TEXT,
    trx_inkind_value_usd NUMERIC(18, 6),
    trx_inkind_value_kes NUMERIC(18, 2),
    trx_stdtime_mnths_hh_nr NUMERIC(18, 6)
);
